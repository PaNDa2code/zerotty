/// Map an XKB / X11 keysym to a platform-neutral `Key`.
/// XKB keysyms for printable ASCII characters equal their Unicode codepoints.
pub fn keyFromXkbKeysym(sym: u32) Key {
    // Printable letters — normalise to lowercase
    if (sym >= 'a' and sym <= 'z') return @enumFromInt(sym);
    if (sym >= 'A' and sym <= 'Z') return @enumFromInt(sym + 32);
    if (sym >= '0' and sym <= '9') return @enumFromInt(sym);
    switch (sym) {
        ' '  => return .space,
        '\'' => return .apostrophe,
        ','  => return .comma,
        '-'  => return .minus,
        '.'  => return .period,
        '/'  => return .slash,
        ';'  => return .semicolon,
        '='  => return .equal,
        '['  => return .left_bracket,
        '\\' => return .backslash,
        ']'  => return .right_bracket,
        '`'  => return .grave,
        else => {},
    }
    return switch (sym) {
        0xFF0D, 0xFF8D => .enter,
        0xFF1B         => .escape,
        0xFF08         => .backspace,
        0xFF09         => .tab,
        0xFFFF         => .delete,
        0xFF63         => .insert,
        0xFF52         => .arrow_up,
        0xFF54         => .arrow_down,
        0xFF51         => .arrow_left,
        0xFF53         => .arrow_right,
        0xFF50         => .home,
        0xFF57         => .end,
        0xFF55         => .page_up,
        0xFF56         => .page_down,
        0xFFBE         => .f1,
        0xFFBF         => .f2,
        0xFFC0         => .f3,
        0xFFC1         => .f4,
        0xFFC2         => .f5,
        0xFFC3         => .f6,
        0xFFC4         => .f7,
        0xFFC5         => .f8,
        0xFFC6         => .f9,
        0xFFC7         => .f10,
        0xFFC8         => .f11,
        0xFFC9         => .f12,
        0xFFE1, 0xFFE2 => .left_shift,
        0xFFE3         => .left_ctrl,
        0xFFE4         => .right_ctrl,
        0xFFE9         => .left_alt,
        0xFFEA         => .right_alt,
        0xFFEB         => .left_super,
        0xFFEC         => .right_super,
        0xFFE5         => .caps_lock,
        0xFF7F         => .num_lock,
        0xFF14         => .scroll_lock,
        0xFFB0         => .kp_0,
        0xFFB1         => .kp_1,
        0xFFB2         => .kp_2,
        0xFFB3         => .kp_3,
        0xFFB4         => .kp_4,
        0xFFB5         => .kp_5,
        0xFFB6         => .kp_6,
        0xFFB7         => .kp_7,
        0xFFB8         => .kp_8,
        0xFFB9         => .kp_9,
        0xFFAE         => .kp_decimal,
        0xFFAF         => .kp_divide,
        0xFFAA         => .kp_multiply,
        0xFFAD         => .kp_subtract,
        0xFFAB         => .kp_add,
        0xFFBD         => .kp_equal,
        else           => .unknown,
    };
}

